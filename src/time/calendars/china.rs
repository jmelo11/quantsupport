//! China holiday calendar.
//! Market source: <https://english.sse.com.cn/start/trading/schedule/>.

use super::traits::{ImplCalendar, IsCalendar};
use crate::time::date::Date;
use std::collections::HashSet;

/// Market or regional calendar.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Market {
    /// SSE calendar.
    #[default]
    SSE,
    /// IB calendar.
    IB,
}

/// China business-day calendar.
/// Dated holidays and working weekends cover 2004–2026. Outside that range,
/// only weekends and New Year are applied; use holiday overrides for other closures.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct China {
    market: Market,
    added_holidays: HashSet<Date>,
    removed_holidays: HashSet<Date>,
}

impl China {
    /// Creates a calendar with empty holiday overrides.
    #[must_use]
    pub fn new(market: Market) -> Self {
        Self {
            market,
            ..Self::default()
        }
    }
}

impl ImplCalendar for China {
    fn impl_name(&self) -> String {
        format!("China({:?})", self.market)
    }

    fn impl_is_business_day(&self, date: &Date) -> bool {
        use super::traits as rules;
        // The interbank calendar follows State Council make-up workdays.
        if self.market == Market::IB && rules::dated_holiday(*date, CHINA_WORKDAYS) {
            return true;
        }
        rules::weekday(*date)
            && !rules::dated_holiday(*date, CHINA_HOLIDAYS)
            && !(self.market == Market::SSE && rules::dated_holiday(*date, SSE_EXTRA_CLOSURES))
            && (date.month(), date.day()) != (1, 1)
    }

    fn added_holidays(&self) -> HashSet<Date> {
        self.added_holidays.clone()
    }

    fn removed_holidays(&self) -> HashSet<Date> {
        self.removed_holidays.clone()
    }

    fn add_holiday(&mut self, date: Date) {
        self.removed_holidays.remove(&date);
        self.added_holidays.insert(date);
    }

    fn remove_holiday(&mut self, date: Date) {
        self.added_holidays.remove(&date);
        self.removed_holidays.insert(date);
    }
}
impl IsCalendar for China {}

