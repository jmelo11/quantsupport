//! `SouthKorea` holiday calendar.
//! Market source: <https://global.krx.co.kr/contents/GLB/06/0606/0606030101/GLB0606030101T3.jsp>.

use super::traits::{ImplCalendar, IsCalendar};
use crate::time::date::Date;
use std::collections::HashSet;

/// Market or regional calendar.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Market {
    /// Settlement calendar.
    #[default]
    Settlement,
    /// KRX calendar.
    KRX,
}

/// `SouthKorea` business-day calendar.
///
/// Holiday dates cover 2004–2050 under the rules known in October 2026.
/// Future elections and exceptional closures require updated announcements.
/// Outside that range only weekends, fixed holidays and KRX year-end apply.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct SouthKorea {
    market: Market,
    added_holidays: HashSet<Date>,
    removed_holidays: HashSet<Date>,
}

impl SouthKorea {
    /// Creates a calendar with empty holiday overrides.
    #[must_use]
    pub fn new(market: Market) -> Self {
        Self {
            market,
            ..Self::default()
        }
    }
}

impl ImplCalendar for SouthKorea {
    fn impl_name(&self) -> String {
        format!("SouthKorea({:?})", self.market)
    }

    fn impl_is_business_day(&self, date: &Date) -> bool {
        use super::traits as rules;
        if !rules::weekday(*date) || rules::dated_holiday(*date, KOREA_HOLIDAYS) {
            return false;
        }
        if !(2004..=2050).contains(&date.year()) {
            // Outside the table only fixed holidays are available.
            let fixed = [
                (1, 1),
                (3, 1),
                (5, 1),
                (5, 5),
                (6, 6),
                (7, 17),
                (8, 15),
                (10, 3),
                (10, 9),
                (12, 25),
            ];
            if fixed.contains(&(date.month(), date.day())) {
                return false;
            }
        }
        if self.market == Market::KRX {
            let mut year_end = Date::new(date.year(), 12, 31);
            while !rules::weekday(year_end) || rules::dated_holiday(year_end, KOREA_HOLIDAYS) {
                year_end -= 1;
            }
            return *date != year_end;
        }
        true
    }

    fn added_holidays(&self) -> HashSet<Date> {
        self.added_holidays.clone()
    }

    fn removed_holidays(&self) -> HashSet<Date> {
        self.removed_holidays.clone()
    }

    fn add_holiday(&mut self, date: Date) {
        self.removed_holidays.remove(&date);
        self.added_holidays.insert(date);
    }

    fn remove_holiday(&mut self, date: Date) {
        self.added_holidays.remove(&date);
        self.removed_holidays.insert(date);
    }
}
impl IsCalendar for SouthKorea {}

