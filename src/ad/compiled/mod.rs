//! Experimental Cranelift numerical AD compiler (opt-in `jit` feature).
//!
//! Captures scalar-generic QS arithmetic once into a replayable operation
//! graph, compiles both the value and reverse gradient into native code, and
//! executes the same code concurrently with private inputs and adjoints.
//!
//! This is an initial *numerical kernel* backend. It does not automatically
//! compile polymorphic `Pricer::evaluate` implementations, dynamic loop
//! structure, curves, calibration or the existing node-weight-only `Tape`.
//! A `Recorded` scalar can, however, run existing `Scalar`-generic math
//! without adding AD nodes to the production tape.
//!
//! # Example
//!
//! ```
//! # #[cfg(feature = "jit")] {
//! use quantsupport::ad::compiled::Graph;
//! use quantsupport::ad::scalar::Scalar;
//!
//! let graph = Graph::trace(&[2.0, 3.0], |x| {
//!     x[0] * x[0] + x[0] * x[1] + x[1].sin()
//! })?;
//! let kernel = graph.compile()?;
//! let mut gradients = vec![0.0; kernel.input_count()];
//! let value = kernel.value_and_grad(&[4.0, 5.0], &mut gradients)?;
//! assert!((value - (16.0 + 20.0 + 5.0_f64.sin())).abs() < 1e-12);
//! assert!((gradients[0] - 13.0).abs() < 1e-12);
//! # }
//! # Ok::<(), Box<dyn std::error::Error>>(())
//! ```

use std::sync::{Arc, Mutex};

use cranelift_jit::JITModule;
use rayon::prelude::*;

mod graph;
mod jit;

pub use graph::{Graph, Recorded};

/// Errors raised by recording, native compilation or execution.
#[derive(Debug, thiserror::Error)]
pub enum CompileError {
    /// Recording cannot be recursively nested on the same thread.
    #[error("a QuantSupport compiler recording is already active")]
    NestedCapture,
    /// Internal recording state disappeared.
    #[error("numerical capture was not active")]
    CaptureMissing,
    /// A scalar from another recording was returned.
    #[error("the graph returned a value from a different recording")]
    ForeignValue,
    /// Data-dependent Rust branching or extracted values cannot be replayed.
    #[error("the captured function observes a numerical value or branches on a traced value; use replay-safe numerical operations instead")]
    DynamicControlFlow,
    /// Input array length does not match the graph signature.
    #[error("expected {expected} numerical inputs, got {actual}")]
    InputCount {
        /// Number of expected inputs.
        expected: usize,
        /// Number of supplied inputs.
        actual: usize,
    },
    /// Gradient output array length does not match the graph signature.
    #[error("expected {expected} gradient slots, got {actual}")]
    GradientCount {
        /// Number of expected gradient output slots.
        expected: usize,
        /// Number of supplied gradient slots.
        actual: usize,
    },
    /// A graph input offset does not fit Cranelift's addressing format.
    #[error("the graph input layout exceeds supported address offsets")]
    OffsetOverflow,
    /// Cranelift compilation or JIT code generation failed.
    #[error("Cranelift compilation failed: {0}")]
    Jit(String),
}

/// Native function generated by Cranelift. Each invocation writes exactly one
/// value and `input_count` derivatives into caller-owned buffers.
pub(super) type RawKernel = unsafe extern "C" fn(*const f64, *mut f64, *mut f64);

/// Lifetime owner for the compiled executable pages. The JITModule is
/// *never* accessed during evaluation; the Mutex merely makes its ownership
/// safely shareable across Rayon workers. The last Arc cannot drop while
/// another call still holds a kernel reference.
pub(super) struct KernelOwner {
    pub(super) _module: Mutex<JITModule>,
    pub(super) function: RawKernel,
}

/// Reusable thread-safe compiled value-and-gradient kernel.
///
/// This owns executable memory but NO mutable execution workspace. Each
/// invocation supplies its own input and gradient buffers. All graph values
/// and temporary adjoints are private SSA values / machine stack temporaries.
#[derive(Clone)]
pub struct CompiledKernel {
    pub(super) owner: Arc<KernelOwner>,
    pub(super) input_count: usize,
}

/// Deterministically chunk-reduced (for a fixed Rayon pool size) Monte Carlo
/// value and gradient sums. No normalization is applied to the results.
#[derive(Clone, Debug)]
pub struct PathSums {
    /// Sum of compiled values across all paths.
    pub value: f64,
    /// Component-wise sum of path gradients, in graph input order.
    pub gradients: Vec<f64>,
    /// Number of paths included in the sums.
    pub count: usize,
}

impl PathSums {
    /// Arithmetic mean of the path values, or `None` for zero paths.
    #[must_use]
    pub fn mean(&self) -> Option<f64> {
        (self.count != 0).then(|| self.value / self.count as f64)
    }
}

impl Graph {
    /// Compiles the forward function and its reverse gradient exactly once.
    ///
    /// # Errors
    /// Returns a Cranelift error or an input-offset overflow.
    pub fn compile(&self) -> Result<CompiledKernel, CompileError> {
        jit::compile(self)
    }
}

impl CompiledKernel {
    /// Number of inputs and returned partial derivatives.
    #[must_use]
    pub const fn input_count(&self) -> usize {
        self.input_count
    }

    /// Executes the compiled forward/reverse kernel without allocating or
    /// recording any AD nodes.
    ///
    /// # Errors
    /// Returns an error when buffer lengths do not match the compiled layout.
    pub fn value_and_grad(
        &self,
        inputs: &[f64],
        gradients: &mut [f64],
    ) -> Result<f64, CompileError> {
        if inputs.len() != self.input_count {
            return Err(CompileError::InputCount {
                expected: self.input_count,
                actual: inputs.len(),
            });
        }
        if gradients.len() != self.input_count {
            return Err(CompileError::GradientCount {
                expected: self.input_count,
                actual: gradients.len(),
            });
        }
        let mut output = 0.0_f64;
        // SAFETY: The caller-provided buffers have exactly the compiled
        // lengths; the ABI is validated by the code generator and the
        // executable pages stay alive through self.owner.
        unsafe {
            (self.owner.function)(
                inputs.as_ptr(),
                &raw mut output,
                gradients.as_mut_ptr(),
            );
        }
        Ok(output)
    }

    /// Runs arbitrary independently indexed Monte Carlo scenarios in parallel.
    ///
    /// The callback fills input slots for a path index (including any
    /// externally generated, reproducible random draws). Each Rayon task owns
    /// its private buffers, and the code is shared read-only. Partial results
    /// are collected in stable chunk order before the final reduction, so
    /// floating-point reductions are reproducible for a fixed pool size.
    ///
    /// This function returns raw sums. Callers decide whether / how to
    /// normalize for MC, CVA, DVA and other QS estimators.
    ///
    /// # Errors
    /// Propagates input-generation errors and compiled-kernel buffer errors.
    pub fn sum_paths<F>(&self, count: usize, fill_inputs: F) -> Result<PathSums, CompileError>
    where
        F: Fn(usize, &mut [f64]) -> Result<(), CompileError> + Send + Sync,
    {
        if count == 0 {
            return Ok(PathSums {
                value: 0.0,
                gradients: vec![0.0; self.input_count],
                count: 0,
            });
        }
        let threads = rayon::current_num_threads().max(1);
        let chunks = threads.saturating_mul(4).max(1);
        let chunk_size = count.div_ceil(chunks).max(1);
        let ranges: Vec<(usize, usize)> = (0..count)
            .step_by(chunk_size)
            .map(|start| (start, count.min(start.saturating_add(chunk_size))))
            .collect();

        let partials: Result<Vec<PathSums>, CompileError> = ranges
            .into_par_iter()
            .map(|(start, end)| {
                let mut inputs = vec![0.0; self.input_count];
                let mut path_gradients = vec![0.0; self.input_count];
                let mut totals = PathSums {
                    value: 0.0,
                    gradients: vec![0.0; self.input_count],
                    count: end - start,
                };
                for index in start..end {
                    fill_inputs(index, &mut inputs)?;
                    let value = self.value_and_grad(&inputs, &mut path_gradients)?;
                    totals.value += value;
                    for (sum, delta) in totals.gradients.iter_mut().zip(&path_gradients) {
                        *sum += delta;
                    }
                }
                Ok(totals)
            })
            .collect();
        let mut result = PathSums {
            value: 0.0,
            gradients: vec![0.0; self.input_count],
            count,
        };
        for partial in partials? {
            result.value += partial.value;
            for (sum, delta) in result.gradients.iter_mut().zip(partial.gradients) {
                *sum += delta;
            }
        }
        Ok(result)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ad::{dual::DualFwd, scalar::Scalar, tape::Tape};

    #[test]
    fn value_and_gradient_reuse() -> Result<(), CompileError> {
        let graph = Graph::trace(&[2.0, 3.0], |x| {
            x[0] * x[0] + x[0] * x[1] + x[1].sin()
        })?;
        let compiled = graph.compile()?;
        let mut gradient = vec![0.0; 2];
        for (x, y) in [(2.0, 3.0), (4.0, 5.0), (-3.0, 2.0)] {
            let value = compiled.value_and_grad(&[x, y], &mut gradient)?;
            assert!((value - (x*x + x*y + y.sin())).abs() < 1e-10);
            assert!((gradient[0] - (2.0*x + y)).abs() < 1e-10);
            assert!((gradient[1] - (x + y.cos())).abs() < 1e-10);
        }
        Ok(())
    }

    #[test]
    fn compare_with_existing_dualfwd() -> Result<(), CompileError> {
        let graph = Graph::trace(&[2.0, 3.0], |x| x[0] * x[1] + x[0])?;
        let compiled = graph.compile()?;
        let mut gradients = [0.0; 2];
        let compiled_value = compiled.value_and_grad(&[2.0, 3.0], &mut gradients)?;
        Tape::start_recording_fwd();
        let x = DualFwd::new(2.0);
        let y = DualFwd::new(3.0);
        let output: DualFwd = (x * y + x).into();
        output.backward().expect("existing AD backward must succeed");
        assert_eq!(compiled_value, output.value());
        assert_eq!(gradients, [x.adjoint().expect("x adjoint").value(), y.adjoint().expect("y adjoint").value()]);
        Tape::stop_recording_fwd();
        Ok(())
    }

    #[test]
    fn rejects_input_dependent_branches() {
        let result = Graph::trace(&[1.0], |x| {
            if x[0] > 0.0 { x[0] } else { -x[0] }
        });
        assert!(matches!(result, Err(CompileError::DynamicControlFlow)));
    }

    #[test]
    fn max_derivative_agrees_with_qs_tie_policy() -> Result<(), CompileError> {
        let graph = Graph::trace(&[3.0, 2.0], |x| x[0].max_val(x[1]))?;
        let compiled = graph.compile()?;
        let mut gradient = [0.0; 2];
        assert_eq!(compiled.value_and_grad(&[3.0, 2.0], &mut gradient)?, 3.0);
        assert_eq!(gradient, [1.0, 0.0]);
        assert_eq!(compiled.value_and_grad(&[2.0, 2.0], &mut gradient)?, 2.0);
        assert_eq!(gradient, [0.0, 0.0]);
        Ok(())
    }

    #[test]
    fn rayon_parallel_sums_are_correct() -> Result<(), CompileError> {
        let graph = Graph::trace(&[2.0, 3.0], |x| x[0] * x[1])?;
        let compiled = graph.compile()?;
        let sums = compiled.sum_paths(10_000, |path, inputs| {
            inputs[0] = path as f64;
            inputs[1] = 2.0;
            Ok(())
        })?;
        assert_eq!(sums.count, 10_000);
        assert_eq!(sums.value, 99_990_000.0);
        assert_eq!(sums.gradients, [20_000.0, 49_995_000.0]);
        Ok(())
    }
}
